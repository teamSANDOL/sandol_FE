import { isoDate } from '@/core/utils/dateFormatter';

/**
 * 대한민국 공휴일(대체공휴일 포함). 음력 · 대체공휴일 때문에 계산할 수 없어 연도별로 적는다.
 * 목록에 없는 연도는 요일만으로 판정한다(공휴일을 평일로 취급). 매년 월력요항이 나오면 추가한다.
 * 출처: 2026 — 관공서의 공휴일에 관한 규정, 2027 — 2026-06 월력요항 기준. 임시공휴일은 지정 시점에 추가.
 */
export const COVERED_YEARS: ReadonlySet<number> = new Set([2026, 2027]);

const DATES: ReadonlySet<string> = new Set([
  // 2026
  '2026-01-01',
  '2026-02-16', '2026-02-17', '2026-02-18', // 설 연휴
  '2026-03-01', '2026-03-02', // 삼일절 + 대체
  '2026-05-01', // 노동절
  '2026-05-05', // 어린이날
  '2026-05-24', '2026-05-25', // 부처님오신날 + 대체
  '2026-06-03', // 전국동시지방선거
  '2026-06-06', // 현충일
  '2026-07-17', // 제헌절
  '2026-08-15', '2026-08-17', // 광복절 + 대체
  '2026-09-24', '2026-09-25', '2026-09-26', // 추석 연휴
  '2026-10-03', '2026-10-05', // 개천절 + 대체
  '2026-10-09', // 한글날
  '2026-12-25', // 성탄절
  // 2027
  '2027-01-01',
  '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09', // 설 연휴 + 대체
  '2027-03-01',
  '2027-05-01', '2027-05-03', // 노동절 + 대체
  '2027-05-05',
  '2027-05-13', // 부처님오신날
  '2027-06-06', // 현충일(일, 대체 없음)
  '2027-07-17', '2027-07-19', // 제헌절 + 대체
  '2027-08-15', '2027-08-16', // 광복절 + 대체
  '2027-09-14', '2027-09-15', '2027-09-16', // 추석 연휴
  '2027-10-03', '2027-10-04', // 개천절 + 대체
  '2027-10-09', '2027-10-11', // 한글날 + 대체
  '2027-12-25', '2027-12-27', // 성탄절 + 대체
]);

/** KST 벽시계 Date(getUTC*)의 연도가 목록에 포함되는지 */
export const coversYear = (d: Date): boolean => COVERED_YEARS.has(d.getUTCFullYear());

/** KST 벽시계 Date 가 공휴일인지. 목록 밖 연도는 항상 false */
export const isHoliday = (d: Date): boolean => DATES.has(isoDate(d));
