import 'package:handori/core/utils/date_formatter.dart';

/// 대한민국 공휴일(대체공휴일 포함) 목록. 셔틀 미운행 판정에 쓴다.
///
/// 공휴일은 음력·대체공휴일 규정 때문에 계산으로 만들 수 없어 연도별로
/// 적어 둔다. 목록에 없는 연도는 [covers]가 false 를 돌려주며, 그때는
/// 요일만으로 판정한다(공휴일을 평일로 취급). 매년 정부 월력요항이
/// 나오면(보통 6월 말) 다음 해 목록을 추가한다.
///
/// 출처: 2026 — 관공서의 공휴일에 관한 규정(제헌절 부활, 노동절 신설 반영),
/// 2027 — 2026-06 월력요항 기준 대체공휴일 규정 적용. 임시공휴일은 지정
/// 시점에 추가해야 한다.
abstract final class KoreanPublicHolidays {
  static const Set<int> coveredYears = {2026, 2027};

  static const Set<String> _dates = {
    // ── 2026 ──────────────────────────────────────────────────────────
    '2026-01-01', // 신정
    '2026-02-16', '2026-02-17', '2026-02-18', // 설 연휴
    '2026-03-01', // 삼일절(일)
    '2026-03-02', // 삼일절 대체공휴일
    '2026-05-01', // 노동절
    '2026-05-05', // 어린이날
    '2026-05-24', // 부처님오신날(일)
    '2026-05-25', // 부처님오신날 대체공휴일
    '2026-06-03', // 전국동시지방선거
    '2026-06-06', // 현충일
    '2026-07-17', // 제헌절
    '2026-08-15', // 광복절(토)
    '2026-08-17', // 광복절 대체공휴일
    '2026-09-24', '2026-09-25', '2026-09-26', // 추석 연휴
    '2026-10-03', // 개천절(토)
    '2026-10-05', // 개천절 대체공휴일
    '2026-10-09', // 한글날
    '2026-12-25', // 성탄절
    // ── 2027 (월력요항 확정 시 재확인) ─────────────────────────────────
    '2027-01-01', // 신정
    '2027-02-06', '2027-02-07', '2027-02-08', // 설 연휴(설날 일요일)
    '2027-02-09', // 설 연휴 대체공휴일
    '2027-03-01', // 삼일절
    '2027-05-01', // 노동절(토)
    '2027-05-03', // 노동절 대체공휴일
    '2027-05-05', // 어린이날
    '2027-05-13', // 부처님오신날
    '2027-06-06', // 현충일(일, 대체 없음)
    '2027-07-17', // 제헌절(토)
    '2027-07-19', // 제헌절 대체공휴일
    '2027-08-15', // 광복절(일)
    '2027-08-16', // 광복절 대체공휴일
    '2027-09-14', '2027-09-15', '2027-09-16', // 추석 연휴
    '2027-10-03', // 개천절(일)
    '2027-10-04', // 개천절 대체공휴일
    '2027-10-09', // 한글날(토)
    '2027-10-11', // 한글날 대체공휴일
    '2027-12-25', // 성탄절(토)
    '2027-12-27', // 성탄절 대체공휴일
  };

  /// [date]의 연도가 목록에 포함되는지.
  static bool covers(DateTime date) => coveredYears.contains(date.year);

  /// [date](연·월·일만 사용)가 공휴일인지. 목록 밖 연도는 항상 false.
  static bool isHoliday(DateTime date) =>
      _dates.contains(DateFormatter.isoDate(date));
}
